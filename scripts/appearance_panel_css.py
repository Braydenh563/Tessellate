"""Writes frontend/css/appearance-panel-lazy.css (INBOX 1435).

The Appearance quick panel hosts the Settings page's own controls, which the
boot sheets style through `#settings-modal ...`. A control moved out of the
window loses those rules, so this copies the ones that reach a setting row,
fold, switch or heading with `#settings-modal` renamed to `#appearance-panel`,
in source order, so the cascade inside the panel is the cascade in Settings.
One source: `tests/test_appearance_panel.py` fails when the file is stale.

    PYTHONPATH=src .venv/bin/python scripts/appearance_panel_css.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
from _css_paths import CSS_FILES  # noqa: E402

OUT = ROOT / "frontend" / "css" / "appearance-panel-lazy.css"
#: A selector is copied when it reaches one of the page's own parts.
KEEP = re.compile(
    r"\.settings-(section|group|fold)|\.setting-(row|label|check|hint|control|reset|scope|modified)|\.check-row"
    r"|\.checkbox-label|\.help-head|\.graph-help-toggle|\.modal-content \.row|\.select-shell|summary|:is\(\.status, \.muted\)"
)
#: The window's own frame, nav, search and panes that are not this page.
SKIP = re.compile(
    r"\.modal-card|\.modal-nav|-nav\b|\.settings-search|modal-overlay|\.code-block|\.shortcut-list|\.suggested-hardware"
    r"|\.searxng|#pref-|\.prefs-save-row|\.jump-echo|\.status\.|> \.dock|\.help-accordion|\.settings-reset-section"
    r"|\.modal-body|\.provider-option|p\.status"
)


def strip_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def parse(text: str) -> list[tuple[str, object]]:
    """Top-level items: ("rule", (selector, body)) or ("at", (prelude, items))."""
    items: list[tuple[str, object]] = []
    i, n = 0, len(text)
    while i < n:
        j = text.find("{", i)
        if j < 0:
            break
        head = text[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(text[k], 0)
            k += 1
        body = text[j + 1 : k - 1]
        i = k
        if head.startswith("@"):
            if re.match(r"@(media|supports)\b", head):
                items.append(("at", (head, parse(body))))
        else:
            items.append(("rule", (head, body.strip())))
    return items


def split_selectors(head: str) -> list[str]:
    parts, depth, cur = [], 0, ""
    for ch in head:
        depth += ch in "([" and 1 or ch in ")]" and -1 or 0
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    return [p for p in parts if p]


def wanted(selector: str) -> bool:
    return "#settings-modal" in selector and bool(KEEP.search(selector)) and not SKIP.search(selector)


def emit(items: list[tuple[str, object]], pad: str = "") -> list[str]:
    out: list[str] = []
    for kind, value in items:
        if kind == "rule":
            head, body = value  # type: ignore[misc]
            chosen = [s.replace("#settings-modal", "#appearance-panel") for s in split_selectors(head) if wanted(s)]
            if chosen:
                lines = [f"{pad}  {line.strip()};" for line in body.split(";") if line.strip()]
                names = (",\n" + pad).join(chosen)
                out.append(f"{pad}{names} {{\n" + "\n".join(lines) + f"\n{pad}}}")
        else:
            prelude, inner = value  # type: ignore[misc]
            made = emit(inner, pad + "  ")
            if made:
                out.append(f"{pad}{prelude} {{\n" + "\n".join(made) + f"\n{pad}}}")
    return out


def build() -> str:
    head = (
        "/* Generated by scripts/appearance_panel_css.py: the Settings window's rules for a setting row,\n"
        "   fold, switch and heading, under #appearance-panel (INBOX 1435). Do not edit; the panel's own\n"
        "   rules are in appearance-panel-own-lazy.css. */\n"
    )
    blocks: list[str] = []
    for path in CSS_FILES:
        if path.name == OUT.name or path.name == "appearance-panel-own-lazy.css":
            continue
        blocks += emit(parse(strip_comments(path.read_text(encoding="utf-8"))))
    return head + "\n".join(blocks) + "\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
